// Flattened [emoji, name, keywords, group] rows.
export const EMOJIS = GROUPS.flatMap(([group, rows]) => rows.map(([e, name, kw]) => [e, name, kw, group]))

export const GROUP_NAMES = GROUPS.map(([g]) => g)

// Rows whose name or keywords contain the query, optionally within one group.
export function filterEmojis(query, group = '') {
  const q = query.trim().toLowerCase()
  return EMOJIS.filter(([, name, kw, g]) => {
    if (group && g !== group) return false
    if (!q) return true
    return `${name} ${kw}`.toLowerCase().includes(q)
  })
}

// Every representation of one emoji developers reach for.
export function emojiFormats(emoji) {
  const points = [...emoji].map((c) => c.codePointAt(0))
  return {
    char: emoji,
    unicode: points.map((p) => `U+${p.toString(16).toUpperCase().padStart(4, '0')}`).join(' '),
    html: points.map((p) => `&#x${p.toString(16).toUpperCase()};`).join(''),
    js: points.map((p) => `\\u{${p.toString(16).toUpperCase()}}`).join(''),
    css: points.map((p) => `\\${p.toString(16).toUpperCase()}`).join(''),
  }
}
